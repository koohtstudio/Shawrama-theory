// Generates lib/photos.generated.ts: width, height and a tiny blur placeholder for every file in public/photos.
import { readdirSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import sharp from "sharp";

const dir = join(process.cwd(), "public/photos");
async function main() {
const out: Record<string, { w: number; h: number; blur: string }> = {};
for (const f of readdirSync(dir).filter((x) => /\.(jpe?g|png|webp)$/i.test(x)).sort()) {
  const img = sharp(join(dir, f));
  const meta = await img.metadata();
  const buf = await img.resize(12).webp({ quality: 40 }).toBuffer();
  out[`/photos/${f}`] = { w: meta.width ?? 0, h: meta.height ?? 0, blur: `data:image/webp;base64,${buf.toString("base64")}` };
}
writeFileSync(
  join(process.cwd(), "lib/photos.generated.ts"),
  `// Generated by scripts/make-blur.ts. Do not edit.\nexport const PHOTOS: Record<string, { w: number; h: number; blur: string }> = ${JSON.stringify(out, null, 2)};\n`,
);
console.log(`wrote ${Object.keys(out).length} photos`);
}
main();
